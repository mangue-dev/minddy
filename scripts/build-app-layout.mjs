import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export async function renderAppLayoutBootstrap() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["lib/app-layout-bootstrap.ts"],
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "es2022",
    minify: true,
    write: false,
    legalComments: "none",
  });
  return result.outputFiles[0].text.trim();
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const script = await renderAppLayoutBootstrap();
  await writeFile(resolve(root, "lib/app-layout-bootstrap.generated.ts"),
    `// Generated by npm run build:app-layout. Do not edit manually.\nexport const APP_LAYOUT_BOOTSTRAP = ${JSON.stringify(script)};\n`);
  console.log("Built the static application layout bootstrap.");
}
