/**
 * PR detail panel (MIN-66 + MIN-138 + MIN-143): header (ticket +
 * status + actions), CI checks banner, then two GitHub-style tabs — the thread
 * conversation (PR description + comments) and modified files.
 * Everything is controlled by `item.prId`: since MIN-143 the PR no longer belongs to the run
 * who opened it, and a human PR has none.
 *
 * A run still controls the “Generated by Numo” badge. All provider actions remain
 * available without a run: review, comments, closing, readiness, and merge.
 * “Fix feedback” may start from the current PR head even when Numo did not create it.
 */

/** Status badge of a check. `pending` pulse: this is the only state that moves. */
function CheckDot({ state, className }: { state: CheckState; className?: string }) {
  return (
    <span
      className={cn(
        "size-2 shrink-0 rounded-full",
        state === "success" && "bg-emerald-500",
        state === "failure" && "bg-destructive",
        state === "pending" && "animate-pulse bg-amber-500",
        state === "neutral" && "bg-muted-foreground/50",
        className,
      )}
    />
  );
}

/**
 * Logo of the integration that produced the check — GitHub serves the REAL logo of
 * each App (Vercel, Socket Security, GitHub Actions, etc.), this is what we display
 * rather than a generic icon. Fallback is the icon of the forge: at GitLab
 * the CI is GitLab, and there is no other logo to show.
 *
 * Neutral background behind the image: many of these logos are transparent and
 * monochrome — without it, a black logo disappears in a dark theme.
 */
function CheckLogo({ url, provider }: { url: string | null; provider: RepoProviderId }) {
  if (url) {
    return (
      // eslint-disable-next-line @next/next/no-img-element
      <img
        src={url}
        alt=""
        className="size-5 shrink-0 rounded-[4px] bg-muted object-cover"
      />
    );
  }
  const Icon = provider === "gitlab" ? Gitlab : Github;
  return (
    <Icon className="size-5 shrink-0 rounded-[4px] bg-muted p-0.5 text-muted-foreground" />
  );
}

/** “42 s”, “3 min 7 s”. `null` when the forge does not date the check. */
function checkDuration(
  t: ReturnType<typeof useTranslations<"PullRequests">>,
  durationMs: number | null,
): string | null {
  if (durationMs == null || !Number.isFinite(durationMs) || durationMs < 0) return null;
  const seconds = Math.round(durationMs / 1000);
  return seconds < 60
    ? t("checkDurationSeconds", { seconds })
    : t("checkDurationMinutes", {
        minutes: Math.floor(seconds / 60),
        seconds: seconds % 60,
      });
}

/** The word of the state, for the checks of which the forge says nothing more. */
const CHECK_STATE_KEY: Record<CheckState, MessageKey<"PullRequests">> = {
  success: "checkStateSuccess",
  failure: "checkStateFailure",
  pending: "checkStatePending",
  neutral: "checkStateNeutral",
};

/**
 * CI check strip. Folded it fits in one line (“3/4 successful”); unfolded
 * it lists each check as GitHub does: the integration logo, the name
 * of the check, what the forge says about the result, its duration, and the link to the forge.
 *
 * Three different “no checks”, and they don’t say the same:
 * `error` = we could not read (permission of the GitHub App not accepted by
 * installation), `total === 0` = this repository has no CI, and the normal case.
 */
function ChecksBanner({
  checks,
  error,
  provider,
  loading,
}: {
  checks: ChecksSummary | null;
  error: "forbidden" | "unknown" | null;
  provider: RepoProviderId;
  loading: boolean;
}) {
  const t = useTranslations("PullRequests");
  const [open, setOpen] = useState(false);
  const now = useNow({ updateInterval: 1_000 });

  if (loading) return <p className="text-xs text-muted-foreground">{t("checksLoading")}</p>;
  if (error) {
    return (
      <p className="text-xs text-muted-foreground">
        {t(error === "forbidden" ? "checksForbidden" : "checksUnknown")}
      </p>
    );
  }
  if (!checks) return <p className="text-xs text-muted-foreground">{t("checksUnknown")}</p>;
  if (checks.total === 0) {
    return <p className="text-xs text-muted-foreground">{t("checksNone")}</p>;
  }

  const label =
    checks.state === "failure"
      ? t("checksFailing", { passing: checks.passing, total: checks.total })
      : checks.state === "pending"
        ? t("checksPending", { passing: checks.passing, total: checks.total })
        : t("checksPassing", { total: checks.total });
  const totalDuration = checks.startedAt
    ? checkDuration(
        t,
        Math.max(
          0,
          (checks.completedAt ? Date.parse(checks.completedAt) : now.getTime()) -
            Date.parse(checks.startedAt),
        ),
      )
    : null;

  return (
    <div data-testid="pr-checks" className="rounded-lg border border-border bg-card">
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        className="flex w-full items-center gap-2 px-3.5 py-2.5 text-left outline-none"
      >
        <CheckDot state={checks.state ?? "neutral"} />
        <span className="text-sm font-medium">{label}</span>
        {totalDuration ? (
          <span className="ml-auto text-xs tabular-nums text-muted-foreground">{totalDuration}</span>
        ) : null}
        {open ? <ChevronDown className="size-4 text-muted-foreground" /> : <ChevronRight className="size-4 text-muted-foreground" />}
      </button>
      {open ? (
        <ul className="flex flex-col divide-y divide-border border-t border-border">
          {checks.checks.map((c) => {
            const duration = checkDuration(
              t,
              c.state === "pending" && c.startedAt
                ? Math.max(0, now.getTime() - Date.parse(c.startedAt))
                : c.durationMs,
            );
            // What the forge says about the result, otherwise the status word: “Failed”
            // only a second empty line under the name remains more useful.
            const detail = [c.appName, c.description ?? t(CHECK_STATE_KEY[c.state])]
              .filter(Boolean)
              .join(" · ");
            return (
              <li
                key={c.name}
                data-testid="pr-check"
                data-required={c.required == null ? "unknown" : String(c.required)}
                className="flex items-center gap-2.5 px-3.5 py-2.5"
              >
                <CheckDot state={c.state} />
                <CheckLogo url={c.appAvatarUrl} provider={provider} />
                <div className="min-w-0 flex-1">
                  <p className="flex min-w-0 items-center gap-1.5 text-sm">
                    <span className="truncate">{c.name}</span>
                    {c.required !== false ? (
                      <Badge
                        data-testid="pr-check-requirement"
                        variant="secondary"
                        className="h-4 shrink-0 px-1.5 text-[9px]"
                      >
                        {t(
                          c.required === true
                            ? "checkRequired"
                            : "checkRequirednessUnknown",
                        )}
                      </Badge>
                    ) : null}
                  </p>
                  <p className="truncate text-xs text-muted-foreground">{detail}</p>
                </div>
                {duration ? (
                  <span className="shrink-0 text-xs tabular-nums text-muted-foreground">
                    {duration}
                  </span>
                ) : null}
                {c.url ? (
                  <a
                    href={c.url}
                    target="_blank"
                    rel="noreferrer"
                    className="inline-flex shrink-0 items-center gap-1 text-xs text-brand hover:underline"
                  >
                    {t("checkDetails")}
                    <ExternalLink className="size-3" />
                  </a>
                ) : null}
              </li>
            );
          })}
        </ul>
      ) : null}
    </div>
  );
}

/**
 * An entry from the conversation thread, messages AND activity combined (MIN-159).
 * The thread is ONE chronological sequence, like on GitHub: a comment, a
 * review, a push and a title change are read in the order in which they were
 * took place, not in three separate lists.
 */
type FeedEntry =
  | { key: string; id: string; createdAt: string | null; kind: "comment"; comment: PullRequestComment }
  | { key: string; id: string; createdAt: string | null; kind: "event"; event: PrTimelineEvent }
  | {
      key: string;
      id: string;
      createdAt: string | null;
      kind: "review";
      event: PrTimelineEvent;
      comments: PullRequestReviewComment[];
    };

/**
 * Messages + activity, merged and put back in order.
 *
 * Four rules carry the entire result:
 * - a commit is signed by its forge ACCOUNT, not by the written `user.name`
 * inside (`resolveCommitActors`): the timeline only knows the second, and
 * the list of commits — already loaded for its tab — is the first one;
 * - CONSECUTIVE commits fold into a single “pushed N commits”
 * (`groupTimelineCommits`), otherwise a PR of twenty commits would drown out the
 *    trois messages qui comptent ;
 * - reviews without a body by the same author fold in the same way
 * (`groupTimelineReviews`): at GitHub, a single point IS a review,
 * and a pass from Numo drops a dozen in a row;
 * - a review becomes a MAP as soon as it has something to say — a body,
 * or points placed on the code. A bare approval remains a line: it
 * has no content, and giving it an empty card would be lying about its weight.
 */
function buildFeed(
  comments: PullRequestComment[],
  timeline: PrTimelineEvent[],
  reviewComments: PullRequestReviewComment[],
  commits: PullRequestCommit[],
): FeedEntry[] {
  const commentsByReview = new Map<number, PullRequestReviewComment[]>();
  for (const comment of reviewComments) {
    if (comment.review_id == null) continue;
    const list = commentsByReview.get(comment.review_id);
    if (list) list.push(comment);
    else commentsByReview.set(comment.review_id, [comment]);
  }

  const entries: FeedEntry[] = comments.map((comment) => ({
    key: `comment:${comment.id}`,
    id: `comment:${comment.id}`,
    createdAt: comment.created_at,
    kind: "comment",
    comment,
  }));

  // Order matters: counts first, otherwise grouping commits
  // would compare git names where two pushes from the same account should meet
  // recognize.
  const events = groupTimelineReviews(
    groupTimelineCommits(resolveCommitActors(timeline, commits)),
  );
  for (const event of events) {
    if (event.kind === "reviewed") {
      const own = (event.reviewIds ?? []).flatMap((id) => commentsByReview.get(id) ?? []);
      if (event.body || own.length > 0) {
        entries.push({
          key: event.id,
          id: event.id,
          createdAt: event.createdAt,
          kind: "review",
          event,
          comments: own,
        });
        continue;
      }
    }
    entries.push({ key: event.id, id: event.id, createdAt: event.createdAt, kind: "event", event });
  }

  return sortTimelineOlderFirst(entries);
}

/**
 * A thread entry: avatar, author, time, markdown body, reactions. Serves
 * as much to the description of the PR (the comment which OPENS the thread) as to the
 * comments that follow — on the GitHub side it's the same thing, and the thread doesn't read
 * like a thread only if its first message has the same shape as the others.
 *
 * This equality also applies to reactions (MIN-147): `commentId` is worth
 * `PR_BODY_COMMENT_ID` for the description, what the server translates into the
 * subject that every forge is waiting for. Reacting therefore works EVERYWHERE in PR — the thread
 * like the diff — instead of just comments anchored to a line of code.
 */
function ThreadComment({
  commentId,
  user,
  createdAt,
  body,
  onQuoteReply,
  quotingNumo,
  reactions,
  activity,
}: {
  commentId: number;
  user: { login: string; avatar_url: string | null } | null;
  createdAt: string | null;
  body: string;
  /** Absent when there is no composition where to cite: to cite without power
      answering leads nowhere (MIN-144). */
  onQuoteReply?: () => void;
  /** This message is from Numo: quote RAPPELLE (MIN-162), and the gesture is called
      otherwise — “Reply with quote” does not say it will re-roll a pass. */
  quotingNumo?: boolean;
  /** Absent when the forge has not been able to read them: nothing is then displayed. */
  reactions?: CommentReactions;
  /** Unrolled folded ABOVE the body, for the message which carries one — the
      Numo's review is the only case: his verdict is the message, his work
      is what produced it. */
  activity?: React.ReactNode;
}) {
  const t = useTranslations("PullRequests");
  const format = useFormatter();
  const now = useNow();
  const list = reactions?.byComment.get(commentId) ?? [];

  return (
    <li className="group/comment flex flex-col gap-1.5 rounded-lg border border-border bg-card px-3.5 py-3">
      <div className="flex items-center gap-2">
        <UserAvatar
          url={user?.avatar_url}
          seed={user?.login ?? "?"}
          className="size-5"
        />
        <GitLogin
          login={user?.login}
          className="text-sm font-medium text-foreground"
        />
        {normalizeForgeInstant(createdAt, now) ? (
          <span className="shrink-0 text-xs text-muted-foreground/80">
            {format.relativeTime(normalizeForgeInstant(createdAt, now) as Date, now)}
          </span>
        ) : null}
        <span className="min-w-0 flex-1" />
        {/* The fallback of the header, for a message WITHOUT reaction: as soon as it
            wears one, the palette moves down into the reaction band, with the
            emoji she adds. Here it is revealed on hover, as
            “Quote” to the right — a permanent palette under each message
            would make a checkerboard of buttons. Returned anyway (and not mounted on
            hover) to remain accessible on the keyboard. */}
        {reactions?.canReact && list.length === 0 ? (
          <ReactionPicker
            className="-my-1 opacity-0 transition-opacity group-hover/comment:opacity-100 focus-visible:opacity-100"
            onPick={reactionToggler(reactions, commentId, list)}
          />
        ) : null}
        {onQuoteReply ? (
          <Tooltip>
            <TooltipTrigger asChild>
              <Button
                variant="ghost"
                size="icon-sm"
                aria-label={t(quotingNumo ? "quoteReplyNumo" : "quoteReply")}
                className="-my-1 size-7 rounded-full text-muted-foreground opacity-0 transition-opacity group-hover/comment:opacity-100 focus-visible:opacity-100"
                onClick={onQuoteReply}
              >
                <Reply className="size-4" />
              </Button>
            </TooltipTrigger>
            <TooltipContent side="top">
              {t(quotingNumo ? "quoteReplyNumo" : "quoteReply")}
            </TooltipContent>
          </Tooltip>
        ) : null}
      </div>
      {/* The scroll is placed at a distance from the header: stuck to the name, it read
          as a second signature line. */}
      {activity ? <div className="pt-1.5">{activity}</div> : null}
      <Markdown className="text-foreground [&_code]:bg-primary/10 [&_code]:text-primary [&_pre_code]:text-inherit">
        {body}
      </Markdown>
      {reactions && list.length > 0 ? (
        <CommentReactionChips commentId={commentId} reactions={reactions} list={list} />
      ) : null}
    </li>
  );
}

