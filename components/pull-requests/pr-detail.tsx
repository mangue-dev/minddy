  // different things.
  const aiReviewLabel = aiReviewActive
    ? t("numoReviewRunning")
    : reviewUpToDate
      ? t("numoReviewUpToDateShort")
      : reviewSession.run
        ? t("numoReviewRerun")
        : t("aiReview");

